// Generates migrations/../seed/seed.sql from seed/questions.ts
// Run with: node scripts/build-seed.mjs
import { writeFileSync } from "node:fs";
import { seedQuestions } from "../seed/questions.ts";

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function assertQuestion(q, idx) {
  const errors = [];
  if (!Array.isArray(q.options) || q.options.length !== 4) {
    errors.push(`question #${idx} must have exactly 4 options`);
  }
  if (typeof q.correctIndex !== "number" || q.correctIndex < 0 || q.correctIndex > 3) {
    errors.push(`question #${idx} correctIndex out of range`);
  }
  if ((q.mode === "WHO_AM_I" || q.mode === "CAREER_PATH") && (!q.clues || q.clues.length < 2)) {
    errors.push(`question #${idx} (${q.mode}) needs at least 2 clues`);
  }
  if (!q.scopes || q.scopes.length === 0) {
    errors.push(`question #${idx} has no scopes`);
  }
  if (errors.length) throw new Error(errors.join("; "));
}

const lines = [];
lines.push("-- Auto-generated by scripts/build-seed.mjs — do not edit by hand.");
lines.push("-- Regenerate with: node scripts/build-seed.mjs");
lines.push("DELETE FROM question_scopes;");
lines.push("DELETE FROM question_clues;");
lines.push("DELETE FROM question_options;");
lines.push("DELETE FROM questions;");
lines.push("");

let counts = { total: 0, byDifficulty: {}, byMode: {} };

seedQuestions.forEach((q, idx) => {
  assertQuestion(q, idx);
  counts.total++;
  counts.byDifficulty[q.difficulty] = (counts.byDifficulty[q.difficulty] || 0) + 1;
  counts.byMode[q.mode] = (counts.byMode[q.mode] || 0) + 1;

  const publicId = `q_${String(idx + 1).padStart(4, "0")}`;
  lines.push(
    `INSERT INTO questions (public_id, mode, category, difficulty, question_he, explanation_he, verified, active, source_label) VALUES ('${publicId}', '${q.mode}', '${q.category}', '${q.difficulty}', '${sqlEscape(q.questionHe)}', '${sqlEscape(q.explanationHe)}', 1, 1, '${sqlEscape(q.sourceLabel)}');`
  );
  lines.push(
    `INSERT INTO question_options (question_id, answer_text, is_correct, sort_order) SELECT id, '${sqlEscape(
      q.options[0]
    )}', ${q.correctIndex === 0 ? 1 : 0}, 0 FROM questions WHERE public_id = '${publicId}';`
  );
  q.options.forEach((opt, optIdx) => {
    if (optIdx === 0) return; // already inserted above to anchor the subquery pattern
    lines.push(
      `INSERT INTO question_options (question_id, answer_text, is_correct, sort_order) SELECT id, '${sqlEscape(
        opt
      )}', ${optIdx === q.correctIndex ? 1 : 0}, ${optIdx} FROM questions WHERE public_id = '${publicId}';`
    );
  });
  (q.clues || []).forEach((clue, clueIdx) => {
    lines.push(
      `INSERT INTO question_clues (question_id, clue_he, sort_order) SELECT id, '${sqlEscape(
        clue
      )}', ${clueIdx} FROM questions WHERE public_id = '${publicId}';`
    );
  });
  (q.scopes || []).forEach((scope) => {
    lines.push(
      `INSERT INTO question_scopes (question_id, scope_type, scope_value) SELECT id, '${scope.type}', '${sqlEscape(
        scope.value
      )}' FROM questions WHERE public_id = '${publicId}';`
    );
  });
  lines.push("");
});

writeFileSync(new URL("../seed/seed.sql", import.meta.url), lines.join("\n"));

console.log(`Generated seed/seed.sql with ${counts.total} questions.`);
console.log("By difficulty:", counts.byDifficulty);
console.log("By mode:", counts.byMode);
